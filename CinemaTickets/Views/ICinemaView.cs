namespace CinemaTickets.Views
{
    /// <summary>
    /// VIEW (интерфейс). То, что контроллер может "попросить" у окна.
    ///
    /// Зачем интерфейс, а не сразу MainWindow:
    /// контроллер не должен зависеть от конкретного окна WPF. Он знает только,
    /// что у вида есть "показать ошибку", "показать сообщение" и "спросить да/нет".
    /// Окно MainWindow реализует этот интерфейс (через MessageBox и строку статуса),
    /// а при желании его можно заменить другим окном — контроллер не изменится.
    ///
    /// Данные (схему зала, список билетов, цену) вид берёт сам из модели,
    /// когда модель сообщает событием Changed, что она изменилась.
    /// </summary>
    public interface ICinemaView
    {
        /// <summary>Сообщить об ошибке ввода или нарушении правила.</summary>
        void ShowError(string message);

        /// <summary>Сообщить об успешной операции (например, "билет продан").</summary>
        void ShowInfo(string message);

        /// <summary>Задать пользователю вопрос "Да / Нет". Возвращает true, если "Да".</summary>
        bool Confirm(string question);
    }
}
